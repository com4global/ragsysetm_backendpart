def _get_auth_header() -> str:
    """
    D-ID uses HTTP Basic Auth.
    Key formats supported:
      1. Key already starts with 'Basic ' → use directly (from D-ID dashboard copy)
      2. Key contains ':' → already email:key, base64-encode as-is
      3. DID_API_EMAIL is set → combine as email:key then base64-encode
      4. Fallback → base64-encode the raw key alone
    """
    key = DID_API_KEY.strip()
    # Case 1: Dashboard gives 'Basic <base64>' — use directly
    if key.lower().startswith("basic "):
        return key
    # Case 2: key already in email:key plain-text format
    if ":" in key:
        encoded = base64.b64encode(key.encode()).decode()
    # Case 3: combine email + key
    elif DID_API_EMAIL:
        encoded = base64.b64encode(f"{DID_API_EMAIL}:{key}".encode()).decode()
    else:
        # Fallback: encode key alone
        encoded = base64.b64encode(key.encode()).decode()
    return f"Basic {encoded}"

