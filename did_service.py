"""
D-ID Talking Avatar Video Service
Generates realistic AI presenter videos for the Individual Learner role.

Flow:
  1. Receive a text script (already generated by GPT via generate_teacher_dialogue or TTS pipeline)
  2. POST to D-ID /talks endpoint with a stock presenter + the script text (TTS handled by D-ID)
  3. Poll GET /talks/{id} until status == 'done' (usually 30-90 seconds)
  4. Return the result_url (public mp4 URL)

Get a free D-ID API key at: https://www.d-id.com/
Set env var: DID_API_KEY=your_key_here
"""

